#!/bin/bash
REPO_ROOT="${REPO_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../.." && pwd)}"
# ============================================================================
# Set up the SHARED data directory for the scienceworld/gemma-4-31b experiments.
#
# All three experiments (baseline/text-skill/vis-skill) read the
# SAME data through symlinks created here — reusable datasets live in ONE
# place and are never duplicated.
#
# NOTE: skill_selections.json is intentionally NOT symlinked. It is
# GENERATED here (real file) by shared/code/prepare_skill_selections.py from
# the qwen3.8-max annotation, so nothing is ever written back into the
# source experiments. It is model-independent (annotation-driven) and shared
# by all runs.
#
# Run once before any experiment (idempotent).
# ============================================================================
set -euo pipefail

SHARED_DIR="$(cd "$(dirname "$0")" && pwd)"
QWEN_TEXT_CODE="$REPO_ROOT/experiments/scienceworld/qwen3.5-9b/text-skill/code"
QWEN_TEXT_ROOT="$REPO_ROOT/experiments/scienceworld/qwen3.5-9b/text-skill"
QWEN_VIS_ROOT="$REPO_ROOT/experiments/scienceworld/qwen3.5-9b/vis-skill"

echo "Setting up shared data in: $SHARED_DIR"

# Test indices (211 episodes, 24 tasks)
ln -sfn "$QWEN_TEXT_CODE/test_indices.json" "$SHARED_DIR/test_indices.json"

# Skill annotations (qwen3.8-max pre-annotated top-5 per episode)
ln -sfn "$QWEN_TEXT_CODE/science_skill_annotations.json" "$SHARED_DIR/science_skill_annotations.json"

# Procedure generation examples
ln -sfn "$QWEN_TEXT_CODE/scienceworld_overall_procedure_examples.txt" "$SHARED_DIR/scienceworld_overall_procedure_examples.txt"

# Code template
ln -sfn "$QWEN_TEXT_CODE/scienceworld_procedure_code_template.py" "$SHARED_DIR/scienceworld_procedure_code_template.py"

# Skill library (61 skills with SKILL.md)
ln -sfn "$QWEN_TEXT_ROOT/skills_scienceworld" "$SHARED_DIR/skills_scienceworld"

# Rendered skill cards (61 PNGs, renderer v6)
ln -sfn "$QWEN_VIS_ROOT/images/skill_cards_v6" "$SHARED_DIR/skill_cards_v6"

# skill_selections.json: built (not symlinked) by prepare_skill_selections.py
if [ ! -f "$SHARED_DIR/skill_selections.json" ]; then
    echo "[info] skill_selections.json not present yet — it will be generated by"
    echo "       shared/code/prepare_skill_selections.py (hard gate in run_all.sh)."
fi

echo "Done. Shared directory contents:"
ls -la "$SHARED_DIR"
